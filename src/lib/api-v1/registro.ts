// REGISTRO DE RECURSOS = fonte unica da fronteira anti-vazamento da API v1.
//
// Cada Recurso mapeia 1:1 para um model Prisma e declara uma ALLOWLIST de
// campos (recurso.campos). Apenas colunas listadas aqui chegam ao Prisma select
// e ao JSON de saida. Segredos e blobs NUNCA aparecem porque simplesmente nao
// estao na allowlist (deny-by-default):
//   - Agente.senha
//   - InstanciaWhatsApp.credencialRef
//   - IntegracaoMercadoLivre.accessToken / refreshToken
//   - ConfiguracaoCRM.metaCapiToken + logoData/faviconData/logoOrcamentoData (blobs)
//   - Mensagem.raw (payload bruto Evolution)
//   - Pagamento.initPoint (link de checkout ativo)
//   - models Sandbox* (dados de simulacao/teste — fora do escopo de producao)
//
// Classificacao de campo:
//   t()      texto/number/bool/enum/Json simples (copiado como esta)
//   dt()     Date -> ISO 8601 UTC
//   money()  Decimal/number -> string decimal 2 casas (BRL)
//   pii(e)   string sensivel -> mascarada sem read:pii
//   msg()    conteudo de mensagem -> null sem read:mensagens

